//! Checking a database's stored schema on open, and migrating it when the
//! declared one differs.
//!
//! Each entity's tables are named after its fingerprint (`Item@<hex>`), so
//! the tables of an old and a new layout live side by side while a migration
//! copies rows from one to the other. Entities whose fingerprint didn't
//! change keep their tables.
//!
//! Indexes other than foreign keys aren't part of the fingerprint: each has
//! a fingerprint of its own in its table's name, and opening a database
//! builds the index tables it doesn't find from the rows.

use std::collections::BTreeSet;

use redb::{
    Database, MultimapTableHandle, ReadTransaction, ReadableDatabase, ReadableTable, TableHandle, WriteTransaction,
};

use crate::__private::META;
use crate::catalog::{self, LAYOUTS, Layout, SOURCES};
use crate::store::{RowTable, Store, create_row_table, create_table, for_each_row, put, remove};
use crate::{Entity, Error, Result};

/// Implemented on every schema's `Db`. Generated by the macro.
pub trait Schema {
    /// The name and fingerprint of each entity.
    const ENTITIES: &'static [(&'static str, u64)];

    /// The schema module's source, recorded next to each entity's
    /// fingerprint for inspection. It is informational only: fingerprints,
    /// not source text, decide whether a database needs migrating.
    const SOURCE: &'static str;

    /// How each entity is stored, for the catalog. `source` is the key its
    /// layouts record for [`Schema::SOURCE`].
    fn layouts(source: u64) -> Vec<Layout>;

    /// Creates every table of the schema that doesn't exist yet, fills the
    /// index tables among them from the rows already stored, and drops index
    /// tables the schema doesn't declare. Fails if a new unique index finds
    /// a duplicate.
    fn create_tables(tx: &WriteTransaction) -> Result<()>;

    /// Checks every reference and unique value, after a migration wrote rows
    /// without checking references.
    fn verify(tx: &WriteTransaction) -> Result<()>;

    /// Brings a database at the previous schema to this one with the
    /// schema's `#[migrate]` functions, after bringing it to the previous
    /// schema first. `false` if the schema has no `#[migrate]` function.
    fn migrate(db: &Database) -> Result<bool>;
}

/// Implemented on every schema's `ReadTx`, so that a `#[migrate]` function
/// names the schema it migrates from by its first argument.
pub trait SchemaReadTx {
    type Schema: Schema;

    fn from_redb(tx: ReadTransaction) -> Self;

    fn redb(&self) -> &ReadTransaction;
}

/// Implemented on every entity: the table its rows live in, so that a
/// `#[migrate]` function for one entity can read the old schema's rows of
/// it. Generated by the macro.
pub trait Rows: Entity {
    const ROWS: RowTable<Self::Id>;
}

/// Calls `f` with every row of `E` in `old`, in id order, holding at most
/// one page of rows in memory.
pub fn for_each_old<E: Rows>(old: &impl SchemaReadTx, mut f: impl FnMut(E) -> Result<()>) -> Result<()> {
    for_each_row(old.redb(), E::ROWS, |bytes| f(crate::__private::decode(bytes)?))
}

/// The fingerprint `entities` lists for `name`, in const context, where the
/// macro checks that a schema's `#[migrate]` functions cover what changed.
pub const fn fingerprint_of(entities: &[(&str, u64)], name: &str) -> Option<u64> {
    let mut i = 0;
    while i < entities.len() {
        if str_eq(entities[i].0, name) {
            return Some(entities[i].1);
        }
        i += 1;
    }
    None
}

/// The first entity of `old` that `new` doesn't declare.
pub const fn removed<'a>(old: &[(&'a str, u64)], new: &[(&str, u64)]) -> Option<&'a str> {
    let mut i = 0;
    while i < old.len() {
        if fingerprint_of(new, old[i].0).is_none() {
            return Some(old[i].0);
        }
        i += 1;
    }
    None
}

const fn str_eq(a: &str, b: &str) -> bool {
    let (a, b) = (a.as_bytes(), b.as_bytes());
    if a.len() != b.len() {
        return false;
    }
    let mut i = 0;
    while i < a.len() {
        if a[i] != b[i] {
            return false;
        }
        i += 1;
    }
    true
}

/// A compile error message with a name in it: const panics can only format
/// a single `&str`.
pub struct Message {
    buf: [u8; 1024],
    len: usize,
}

impl Message {
    pub const fn new() -> Self {
        Self { buf: [0; 1024], len: 0 }
    }

    /// Appends `s`, or as much of it as fits.
    pub const fn push(mut self, s: &str) -> Self {
        let s = s.as_bytes();
        let mut i = 0;
        while i < s.len() && self.len < self.buf.len() {
            self.buf[self.len] = s[i];
            self.len += 1;
            i += 1;
        }
        self
    }

    pub const fn as_str(&self) -> &str {
        let (bytes, _) = self.buf.split_at(self.len);
        match std::str::from_utf8(bytes) {
            Ok(s) => s,
            Err(e) => match std::str::from_utf8(bytes.split_at(e.valid_up_to()).0) {
                Ok(s) => s,
                Err(_) => "",
            },
        }
    }
}

impl Default for Message {
    fn default() -> Self {
        Self::new()
    }
}

fn fingerprint_key(entity: &str) -> String {
    format!("{entity}.fingerprint")
}

pub(crate) fn seq_key(entity: &str) -> String {
    format!("{entity}.next_id")
}

/// The first entity stored with a fingerprint other than the declared one.
/// Entities the database doesn't hold yet are fine.
fn stale<S: Schema>(tx: &impl Store) -> Result<Option<(&'static str, u64, u64)>> {
    for &(entity, declared) in S::ENTITIES {
        if let Some(stored) = tx.get(META, &fingerprint_key(entity))?
            && stored != declared
        {
            return Ok(Some((entity, stored, declared)));
        }
    }
    Ok(None)
}

/// The first stored entity that `S` doesn't declare but that references one
/// it does. `S` would delete rows without applying that entity's `on_delete`
/// rules, so it can't open the database until the entity is migrated away.
/// Undeclared entities that reference none of `S`'s belong to some other
/// schema and are fine, as are those stored before layouts were recorded,
/// whose references are unknown.
fn undeclared<S: Schema>(tx: &WriteTransaction) -> Result<Option<Error>> {
    let mut stored = Vec::new();
    for entry in tx.open_table(META)?.iter()? {
        let (key, value) = entry?;
        if let Some(entity) = key.value().strip_suffix(".fingerprint") {
            stored.push((entity.to_string(), value.value()));
        }
    }
    for (entity, fingerprint) in stored {
        if S::ENTITIES.iter().any(|(name, _)| *name == entity.as_str()) {
            continue;
        }
        let Some(bytes) = tx.get_row(LAYOUTS, &table_prefix(&entity, fingerprint))? else {
            continue;
        };
        for reference in catalog::decode(&bytes)?.references {
            if let Some(&(target, _)) = S::ENTITIES.iter().find(|(name, _)| *name == reference.target) {
                return Ok(Some(Error::Undeclared {
                    entity,
                    field: reference.field,
                    target,
                }));
            }
        }
    }
    Ok(None)
}

/// Prepares `db` for schema `S`: creates its tables if the stored schema
/// matches, migrates it if `S` knows how, and fails otherwise without
/// changing anything.
pub fn open<S: Schema>(db: &Database) -> Result<()> {
    let tx = db.begin_write()?;
    create_table(&tx, META)?;
    create_table(&tx, SOURCES)?;
    create_row_table(&tx, LAYOUTS)?;
    let mismatch = match stale::<S>(&tx)? {
        Some((entity, stored, declared)) => Error::SchemaMismatch {
            entity,
            stored,
            declared,
        },
        None => match undeclared::<S>(&tx)? {
            Some(undeclared) => undeclared,
            None => {
                S::create_tables(&tx)?;
                record::<S>(&tx)?;
                tx.commit()?;
                return Ok(());
            }
        },
    };
    tx.abort()?;
    match S::migrate(db) {
        Ok(true) => Ok(()),
        Ok(false) => Err(mismatch),
        // Every declared entity is stored as declared, so a migration that
        // finds the database at some other schema doesn't apply: the
        // undeclared entity is the problem to report.
        Err(Error::SchemaMismatch { .. }) if matches!(mismatch, Error::Undeclared { .. }) => Err(mismatch),
        Err(e) => Err(e),
    }
}

fn record<S: Schema>(tx: &WriteTransaction) -> Result<()> {
    for &(entity, fingerprint) in S::ENTITIES {
        put(tx, META, &fingerprint_key(entity), &fingerprint)?;
    }
    catalog::record(tx, &S::layouts(catalog::source_key(S::SOURCE)), S::SOURCE)
}

/// The second half of a migration from `Old` to `New`, once the migration
/// function has written the new rows: checks them, drops the tables of every
/// layout `New` no longer uses and records `New` as the stored schema.
///
/// Entities of `Old` that `New` doesn't declare are dropped. Entities that
/// neither declares belong to someone else and are left alone.
pub fn finish_migration<Old: Schema, New: Schema>(tx: &WriteTransaction) -> Result<()> {
    New::verify(tx)?;
    let names: BTreeSet<&str> = Old::ENTITIES
        .iter()
        .chain(New::ENTITIES)
        .map(|(name, _)| *name)
        .collect();
    for name in names {
        let declared = New::ENTITIES.iter().find(|(n, _)| *n == name).map(|(_, f)| *f);
        if let Some(stored) = tx.get(META, &fingerprint_key(name))?
            && Some(stored) != declared
        {
            drop_tables(tx, name, stored)?;
        }
        if declared.is_none() {
            remove(tx, META, &fingerprint_key(name))?;
            remove(tx, META, &seq_key(name))?;
        }
    }
    record::<New>(tx)
}

/// Deletes the row and index tables of `entity` at `fingerprint`.
fn drop_tables(tx: &WriteTransaction, entity: &str, fingerprint: u64) -> Result<()> {
    let prefix = table_prefix(entity, fingerprint);
    let ours = |name: &str| {
        name.strip_prefix(&prefix)
            .is_some_and(|rest| rest.is_empty() || rest.starts_with('.'))
    };
    let tables: Vec<_> = tx.list_tables()?.filter(|t| ours(t.name())).collect();
    for table in tables {
        tx.delete_table(table)?;
    }
    let tables: Vec<_> = tx.list_multimap_tables()?.filter(|t| ours(t.name())).collect();
    for table in tables {
        tx.delete_multimap_table(table)?;
    }
    Ok(())
}

/// Drops the tables of `entity` at `fingerprint` other than its rows and the
/// tables in `keep`: index tables of an index the schema no longer declares,
/// or declares differently. Keeping them would leave indexes that nothing
/// updates, and a schema that declares them again would trust them.
pub fn drop_other_tables(tx: &WriteTransaction, entity: &str, fingerprint: u64, keep: &[&str]) -> Result<()> {
    let prefix = format!("{}.", table_prefix(entity, fingerprint));
    let stale = |name: &str| name.starts_with(&prefix) && !keep.contains(&name);
    let tables: Vec<_> = tx.list_tables()?.filter(|t| stale(t.name())).collect();
    for table in tables {
        tx.delete_table(table)?;
    }
    let tables: Vec<_> = tx.list_multimap_tables()?.filter(|t| stale(t.name())).collect();
    for table in tables {
        tx.delete_multimap_table(table)?;
    }
    Ok(())
}

pub(crate) fn table_prefix(entity: &str, fingerprint: u64) -> String {
    format!("{entity}@{fingerprint:016x}")
}

/// `{entity}@{fingerprint:016x}{suffix}`, built in const context so that
/// table definitions can stay `const`. `N` is the length of the result.
pub const fn table_name<const N: usize>(entity: &str, fingerprint: u64, suffix: &str) -> [u8; N] {
    let mut out = [0u8; N];
    let mut i = push_layout(&mut out, 0, entity, fingerprint);
    i = push(&mut out, i, suffix);
    assert!(i == N, "table name length mismatch");
    out
}

/// `{entity}@{fingerprint:016x}.{index}@{index_fingerprint:016x}{suffix}`:
/// an index table. It belongs to the entity's layout like its other tables,
/// and its own fingerprint changes whenever what it indexes does, so that a
/// changed index starts out as a new, empty table.
pub const fn index_table_name<const N: usize>(
    entity: &str,
    fingerprint: u64,
    index: &str,
    index_fingerprint: u64,
    suffix: &str,
) -> [u8; N] {
    let mut out = [0u8; N];
    let mut i = push_layout(&mut out, 0, entity, fingerprint);
    i = push(&mut out, i, ".");
    i = push_layout(&mut out, i, index, index_fingerprint);
    i = push(&mut out, i, suffix);
    assert!(i == N, "table name length mismatch");
    out
}

/// Writes `{name}@{fingerprint:016x}` at `i` and returns where it ends.
const fn push_layout(out: &mut [u8], mut i: usize, name: &str, fingerprint: u64) -> usize {
    i = push(out, i, name);
    i = push(out, i, "@");
    let mut nibble = 0;
    while nibble < 16 {
        let digit = ((fingerprint >> (60 - 4 * nibble)) & 0xf) as u8;
        out[i] = if digit < 10 { b'0' + digit } else { b'a' + digit - 10 };
        i += 1;
        nibble += 1;
    }
    i
}

const fn push(out: &mut [u8], mut i: usize, s: &str) -> usize {
    let s = s.as_bytes();
    let mut j = 0;
    while j < s.len() {
        out[i] = s[j];
        i += 1;
        j += 1;
    }
    i
}

pub const fn utf8(bytes: &[u8]) -> &str {
    match std::str::from_utf8(bytes) {
        Ok(s) => s,
        Err(_) => panic!("table names are ASCII"),
    }
}

/// Opens a snapshot for the old side of a migration.
pub fn begin_read(db: &Database) -> Result<ReadTransaction> {
    Ok(db.begin_read()?)
}
