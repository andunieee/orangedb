//! Checking a database's stored schema on open, and migrating it when the
//! declared one differs.
//!
//! Each entity's tables are named after its fingerprint (`Item@<hex>`), so
//! the tables of an old and a new layout live side by side while a migration
//! copies rows from one to the other. Entities whose fingerprint didn't
//! change keep their tables.

use std::collections::BTreeSet;

use redb::{Database, MultimapTableHandle, ReadTransaction, ReadableDatabase, TableHandle, WriteTransaction};

use crate::__private::META;
use crate::catalog::{self, LAYOUTS, Layout, SOURCES};
use crate::store::{Store, create_row_table, create_table, put, remove};
use crate::{Error, Result};

/// Implemented on every schema's `Db`. Generated by the macro.
pub trait Schema {
    /// The name and fingerprint of each entity.
    const ENTITIES: &'static [(&'static str, u64)];

    /// The schema module's source, recorded next to each entity's
    /// fingerprint for inspection. It is informational only: fingerprints,
    /// not source text, decide whether a database needs migrating.
    const SOURCE: &'static str;

    /// How each entity is stored, for the catalog. `source` is the key its
    /// layouts record for [`Schema::SOURCE`].
    fn layouts(source: u64) -> Vec<Layout>;

    /// Creates every table of the schema that doesn't exist yet.
    fn create_tables(tx: &WriteTransaction) -> Result<()>;

    /// Checks every reference and unique value, after a migration wrote rows
    /// without checking references.
    fn verify(tx: &WriteTransaction) -> Result<()>;

    /// Brings a database at the previous schema to this one with the
    /// schema's `#[migrate]` function, after bringing it to the previous
    /// schema first. `false` if the schema has no `#[migrate]` function.
    fn migrate(db: &Database) -> Result<bool>;
}

/// Implemented on every schema's `ReadTx`, so that a `#[migrate]` function
/// names the schema it migrates from by its first argument.
pub trait SchemaReadTx {
    type Schema: Schema;

    fn from_redb(tx: ReadTransaction) -> Self;
}

fn fingerprint_key(entity: &str) -> String {
    format!("{entity}.fingerprint")
}

pub(crate) fn seq_key(entity: &str) -> String {
    format!("{entity}.next_id")
}

/// The first entity stored with a fingerprint other than the declared one.
/// Entities the database doesn't hold yet are fine.
fn stale<S: Schema>(tx: &impl Store) -> Result<Option<(&'static str, u64, u64)>> {
    for &(entity, declared) in S::ENTITIES {
        if let Some(stored) = tx.get(META, &fingerprint_key(entity))?
            && stored != declared
        {
            return Ok(Some((entity, stored, declared)));
        }
    }
    Ok(None)
}

/// Prepares `db` for schema `S`: creates its tables if the stored schema
/// matches, migrates it if `S` knows how, and fails otherwise without
/// changing anything.
pub fn open<S: Schema>(db: &Database) -> Result<()> {
    let tx = db.begin_write()?;
    create_table(&tx, META)?;
    create_table(&tx, SOURCES)?;
    create_row_table(&tx, LAYOUTS)?;
    let Some((entity, stored, declared)) = stale::<S>(&tx)? else {
        S::create_tables(&tx)?;
        record::<S>(&tx)?;
        tx.commit()?;
        return Ok(());
    };
    tx.abort()?;
    if S::migrate(db)? {
        Ok(())
    } else {
        Err(Error::SchemaMismatch {
            entity,
            stored,
            declared,
        })
    }
}

fn record<S: Schema>(tx: &WriteTransaction) -> Result<()> {
    for &(entity, fingerprint) in S::ENTITIES {
        put(tx, META, &fingerprint_key(entity), &fingerprint)?;
    }
    catalog::record(tx, &S::layouts(catalog::source_key(S::SOURCE)), S::SOURCE)
}

/// The second half of a migration from `Old` to `New`, once the migration
/// function has written the new rows: checks them, drops the tables of every
/// layout `New` no longer uses and records `New` as the stored schema.
///
/// Entities of `Old` that `New` doesn't declare are dropped. Entities that
/// neither declares belong to someone else and are left alone.
pub fn finish_migration<Old: Schema, New: Schema>(tx: &WriteTransaction) -> Result<()> {
    New::verify(tx)?;
    let names: BTreeSet<&str> = Old::ENTITIES
        .iter()
        .chain(New::ENTITIES)
        .map(|(name, _)| *name)
        .collect();
    for name in names {
        let declared = New::ENTITIES.iter().find(|(n, _)| *n == name).map(|(_, f)| *f);
        if let Some(stored) = tx.get(META, &fingerprint_key(name))?
            && Some(stored) != declared
        {
            drop_tables(tx, name, stored)?;
        }
        if declared.is_none() {
            remove(tx, META, &fingerprint_key(name))?;
            remove(tx, META, &seq_key(name))?;
        }
    }
    record::<New>(tx)
}

/// Deletes the row and index tables of `entity` at `fingerprint`.
fn drop_tables(tx: &WriteTransaction, entity: &str, fingerprint: u64) -> Result<()> {
    let prefix = table_prefix(entity, fingerprint);
    let ours = |name: &str| {
        name.strip_prefix(&prefix)
            .is_some_and(|rest| rest.is_empty() || rest.starts_with('.'))
    };
    let tables: Vec<_> = tx.list_tables()?.filter(|t| ours(t.name())).collect();
    for table in tables {
        tx.delete_table(table)?;
    }
    let tables: Vec<_> = tx.list_multimap_tables()?.filter(|t| ours(t.name())).collect();
    for table in tables {
        tx.delete_multimap_table(table)?;
    }
    Ok(())
}

pub(crate) fn table_prefix(entity: &str, fingerprint: u64) -> String {
    format!("{entity}@{fingerprint:016x}")
}

/// `{entity}@{fingerprint:016x}{suffix}`, built in const context so that
/// table definitions can stay `const`. `N` is the length of the result.
pub const fn table_name<const N: usize>(entity: &str, fingerprint: u64, suffix: &str) -> [u8; N] {
    let mut out = [0u8; N];
    let mut i = 0;
    let entity = entity.as_bytes();
    let mut j = 0;
    while j < entity.len() {
        out[i] = entity[j];
        i += 1;
        j += 1;
    }
    out[i] = b'@';
    i += 1;
    let mut nibble = 0;
    while nibble < 16 {
        let digit = ((fingerprint >> (60 - 4 * nibble)) & 0xf) as u8;
        out[i] = if digit < 10 { b'0' + digit } else { b'a' + digit - 10 };
        i += 1;
        nibble += 1;
    }
    let suffix = suffix.as_bytes();
    j = 0;
    while j < suffix.len() {
        out[i] = suffix[j];
        i += 1;
        j += 1;
    }
    assert!(i == N, "table name length mismatch");
    out
}

pub const fn utf8(bytes: &[u8]) -> &str {
    match std::str::from_utf8(bytes) {
        Ok(s) => s,
        Err(_) => panic!("table names are ASCII"),
    }
}

/// Opens a snapshot for the old side of a migration.
pub fn begin_read(db: &Database) -> Result<ReadTransaction> {
    Ok(db.begin_read()?)
}
